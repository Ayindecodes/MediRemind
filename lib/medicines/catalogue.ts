// lib/medicines/catalogue.ts
// A starter list of medicines people in Nigeria commonly take, to make typing a medicine's name
// quick. It only suggests: the add form always takes any name. It isn't medical advice, and the
// strengths are examples; people confirm theirs from the pack. Brand names belong to their owners.
//
// It's written from general knowledge, not copied from a registry. NAFDAC's Greenbook
// (greenbook.nafdac.gov.ng) is "all rights reserved" with no terms of use, so it's a place for people
// to check their own pack, not a source for this list.
