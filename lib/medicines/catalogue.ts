export interface CatalogueEntry {
  // The medicine's own name, as pharmacists use it
  name: string;
  // Brand names sold in Nigeria, best known first
  brands: string[];
  // Usual forms, the most common first
  forms: MedicineForm[];
  // Strengths as written on packs, as examples
  strengths: string[];
  // What it's for, in plain words, so people can search by condition
  uses: string[];
  // Only for fixed courses that never vary, such as a 3-day malaria treatment
  course?: Schedule;
  group: Group;
}

